import AppKit
import Carbon

struct ClipEntry: Codable, Identifiable {
    enum Kind: String, Codable { case text, image, files }

    var id = UUID()
    let kind: Kind
    var text: String?
    var files: [String]?
    var imageFile: String?
    var pixelSize: String?
    var date = Date()
    var source: String?
    var sourcePath: String?

    var title: String {
        switch kind {
        case .text:
            let line = (text ?? "").split(whereSeparator: \.isNewline)
                .first { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
                .map { $0.trimmingCharacters(in: .whitespaces) } ?? ""
            return String(line.prefix(140))
        case .image:
            return "Image" + (pixelSize.map { " \($0)" } ?? "")
        case .files:
            let list = files ?? []
            return list.count == 1 ? (list[0] as NSString).lastPathComponent : "\(list.count) fichiers"
        }
    }

    var detail: String {
        switch kind {
        case .text:
            let t = text ?? ""
            let lines = t.split(whereSeparator: \.isNewline).count
            return "\(t.count) caractères · \(max(lines, 1)) ligne\(lines > 1 ? "s" : "")"
        case .image: return "Image PNG" + (pixelSize.map { " · \($0) px" } ?? "")
        case .files: return "\(files?.count ?? 0) élément(s)"
        }
    }

    var imageURL: URL? { imageFile.map { ClipboardHistory.imagesDir.appendingPathComponent($0) } }

    var trimmedText: String { (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines) }

    var hexColor: NSColor? {
        let t = trimmedText
        guard t.count <= 7, t.range(of: "^#?[0-9a-fA-F]{6}$", options: .regularExpression) != nil,
              let v = UInt32(t.replacingOccurrences(of: "#", with: ""), radix: 16) else { return nil }
        return NSColor(srgbRed: CGFloat((v >> 16) & 0xFF) / 255, green: CGFloat((v >> 8) & 0xFF) / 255,
                       blue: CGFloat(v & 0xFF) / 255, alpha: 1)
    }

    var isLink: Bool {
        let t = trimmedText
        return (t.hasPrefix("http://") || t.hasPrefix("https://")) && !t.contains(where: \.isWhitespace)
    }

    var looksLikeCode: Bool {
        guard let t = text else { return false }
        return t.contains("{") || t.contains("\t") || t.contains(";\n") || t.contains("=>") || t.hasPrefix("  ")
    }

    var icon: ItemIcon {
        switch kind {
        case .image: return imageURL.map { .image($0) } ?? .symbol("photo", .purple)
        case .files: return .file(files?.first ?? "/")
        case .text:
            if let c = hexColor { return .color(c) }
            if isLink { return .symbol("link", .blue) }
            return .symbol("text.alignleft", .gray)
        }
    }

    func sameContent(as other: ClipEntry) -> Bool {
        kind == other.kind && kind != .image && text == other.text && files == other.files
    }
}

/// Surveille le presse-papiers en lisant `changeCount` (un entier) : aucune donnée n'est lue
/// tant que rien n'a changé. Les copies marquées "concealed" (gestionnaires de mots de passe) sont ignorées.
final class ClipboardHistory {
    private(set) var entries: [ClipEntry] = []
    var onChange: (() -> Void)?

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var keys: [UUID: String] = [:]
    private var saveScheduled = false
    private let io = DispatchQueue(label: "hello.clipboard.io", qos: .utility)

    static let dir: URL = {
        let url = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Hello", isDirectory: true)
        try? FileManager.default.createDirectory(at: url.appendingPathComponent("Clipboard"),
                                                 withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        return url
    }()
    static var imagesDir: URL { dir.appendingPathComponent("Clipboard", isDirectory: true) }
    private var indexURL: URL { Self.dir.appendingPathComponent("clipboard.json") }

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]

    func start() {
        load()
        prune()
        updateMonitoring()
    }

    /// Démarre / arrête la surveillance selon les réglages (aucun timer si désactivé).
    func updateMonitoring() {
        timer?.invalidate()
        timer = nil
        guard AppSettings.shared.clipboardEnabled else { return }
        lastChange = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.35
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Applique la limite de taille et la durée de conservation.
    func prune() {
        let settings = AppSettings.shared
        var removed = false
        if settings.clipboardRetentionDays > 0 {
            let limit = Date().addingTimeInterval(-Double(settings.clipboardRetentionDays) * 86_400)
            for e in entries where e.date < limit { discard(e); removed = true }
            entries.removeAll { $0.date < limit }
        }
        while entries.count > settings.clipboardLimit {
            discard(entries.removeLast())
            removed = true
        }
        if removed { changed() }
    }

    /// À appeler après avoir écrit nous-mêmes dans le presse-papiers.
    func skipCurrent() {
        lastChange = NSPasteboard.general.changeCount
    }

    func searchKey(_ e: ClipEntry) -> String {
        if let k = keys[e.id] { return k }
        let base: String
        switch e.kind {
        case .text: base = String((e.text ?? "").prefix(4000))
        case .files: base = (e.files ?? []).joined(separator: " ")
        case .image: base = "image " + (e.pixelSize ?? "")
        }
        let k = Fuzzy.fold(base + " " + (e.source ?? ""))
        keys[e.id] = k
        return k
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard let types = pb.types, !types.isEmpty,
              !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        if let id = front?.bundleIdentifier, AppSettings.shared.clipboardIgnored.contains(id) { return }

        var entry: ClipEntry?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            entry = ClipEntry(kind: .files, files: urls.map(\.path))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            entry = ClipEntry(kind: .text, text: s)
        } else if AppSettings.shared.clipboardImages,
                  let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            entry = storeImage(data)
        }
        guard var e = entry else { return }
        e.source = front?.localizedName
        e.sourcePath = front?.bundleURL?.path
        insert(e)
    }

    /// Seules les dimensions sont lues tout de suite (en-tête de l'image) ; la conversion en PNG et l'écriture
    /// se font en arrière-plan : une capture d'écran 5K ne bloque plus le fil principal pendant la copie.
    private func storeImage(_ data: Data) -> ClipEntry? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = props[kCGImagePropertyPixelWidth] as? Int,
              let height = props[kCGImagePropertyPixelHeight] as? Int else { return nil }
        let isPNG = (CGImageSourceGetType(source) as String?) == "public.png"
        var e = ClipEntry(kind: .image)
        let name = e.id.uuidString + ".png"
        e.imageFile = name
        e.pixelSize = "\(width)×\(height)"
        let url = Self.imagesDir.appendingPathComponent(name)
        io.async { [weak self] in
            let png = isPNG ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            try? png?.write(to: url)
            DispatchQueue.main.async { self?.onChange?() }
        }
        return e
    }

    private func insert(_ e: ClipEntry) {
        if let i = entries.firstIndex(where: { $0.sameContent(as: e) }) {
            keys[entries.remove(at: i).id] = nil
        }
        entries.insert(e, at: 0)
        changed()
        prune()
    }

    /// Remet l'élément dans le presse-papiers (et le colle dans l'app active si demandé).
    func restore(_ e: ClipEntry, paste: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch e.kind {
        case .text: pb.setString(e.text ?? "", forType: .string)
        case .image: if let url = e.imageURL, let img = NSImage(contentsOf: url) { pb.writeObjects([img]) }
        case .files: pb.writeObjects((e.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        skipCurrent()
        if let i = entries.firstIndex(where: { $0.id == e.id }) {
            var moved = entries.remove(at: i)
            moved.date = Date()
            entries.insert(moved, at: 0)
            changed()
        }
        if paste { Paster.pasteFrontmost() }
    }

    func remove(_ e: ClipEntry) {
        guard let i = entries.firstIndex(where: { $0.id == e.id }) else { return }
        discard(entries.remove(at: i))
        changed()
    }

    func clear() {
        entries.forEach(discard)
        entries = []
        changed()
    }

    private func discard(_ e: ClipEntry) {
        keys[e.id] = nil
        if let url = e.imageURL { io.async { try? FileManager.default.removeItem(at: url) } }
    }

    private func changed() {
        onChange?()
        guard !saveScheduled else { return }
        saveScheduled = true
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.5) { [weak self] in
            guard let self else { return }
            saveScheduled = false
            let snapshot = entries
            let url = indexURL
            io.async {
                guard let data = try? JSONEncoder().encode(snapshot) else { return }
                try? data.write(to: url, options: .atomic)
                try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            }
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: indexURL),
              let list = try? JSONDecoder().decode([ClipEntry].self, from: data) else { return }
        entries = list
    }
}

enum Paster {
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static var prompted = false

    static var canPaste: Bool { AppSettings.shared.pasteOnEnter && AXIsProcessTrusted() }

    static func copy(_ s: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(s, forType: .string)
    }

    /// Tape un texte dans l'app active (via ⌘V) puis restaure le presse-papiers d'origine.
    /// Sans permission d'accessibilité : se contente de copier.
    static func insert(_ s: String) {
        guard AppSettings.shared.pasteOnEnter, ensureTrusted() else {
            copy(s)
            return
        }
        let pb = NSPasteboard.general
        let saved = snapshot(pb)
        pb.clearContents()
        pb.setString(s, forType: .string)
        pb.setData(Data(), forType: transient)
        Controller.shared.clipboard.skipCurrent()
        pressCommandV()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
            restore(saved, to: pb)
            Controller.shared.clipboard.skipCurrent()
        }
    }

    static func pasteFrontmost() {
        guard AppSettings.shared.pasteOnEnter, ensureTrusted() else { return }
        pressCommandV()
    }

    private static func ensureTrusted() -> Bool {
        if AXIsProcessTrusted() { return true }
        if !prompted {
            prompted = true
            let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
            AXIsProcessTrustedWithOptions(options)
        }
        return false
    }

    private static func pressCommandV() {
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) {
            let source = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
                event?.flags = .maskCommand
                event?.post(tap: .cghidEventTap)
            }
        }
    }

    private static func snapshot(_ pb: NSPasteboard) -> [[(NSPasteboard.PasteboardType, Data)]] {
        (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    private static func restore(_ saved: [[(NSPasteboard.PasteboardType, Data)]], to pb: NSPasteboard) {
        pb.clearContents()
        guard !saved.isEmpty else { return }
        let items = saved.map { pairs -> NSPasteboardItem in
            let item = NSPasteboardItem()
            pairs.forEach { item.setData($0.1, forType: $0.0) }
            return item
        }
        pb.writeObjects(items)
    }
}
